USE master;
GO
IF DB_ID(N'JsonImport') IS NOT NULL
BEGIN
    ALTER DATABASE JsonImport SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE JsonImport;
END
GO
CREATE DATABASE JsonImport;
GO
USE JsonImport;
GO

CREATE SCHEMA stg;
GO

CREATE TABLE stg.JsonDoc
(
    DocId      INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_JsonDoc PRIMARY KEY,
    LoadedAt   DATETIME2(0)  NOT NULL CONSTRAINT DF_JsonDoc_Loaded DEFAULT (SYSDATETIME()),
    SourceFile NVARCHAR(400) NULL,
    Body       NVARCHAR(MAX) NOT NULL
);
GO
